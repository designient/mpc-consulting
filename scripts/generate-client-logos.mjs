import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const clientsRoot = path.join(__dirname, '../public/logos/clients');
const outFile = path.join(__dirname, '../src/data/clientLogos.ts');

const IMAGE_EXT = /\.(png|jpe?g)$/i;

function slugify(filename) {
  return filename
    .replace(IMAGE_EXT, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

function displayName(filename) {
  return filename
    .replace(IMAGE_EXT, '')
    .replace(/[-_]+/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
    .replace(/\b\w/g, (c) => c.toUpperCase());
}

function scanCategory(category) {
  const dir = path.join(clientsRoot, category);
  if (!fs.existsSync(dir)) {
    throw new Error(`Missing logo directory: ${dir}`);
  }

  return fs
    .readdirSync(dir)
    .filter((file) => IMAGE_EXT.test(file) && !file.startsWith('.'))
    .map((file) => {
      const slug = slugify(file);
      const name = displayName(file);
      const prefix = category.toLowerCase();
      return {
        id: `${prefix}-${slug}`,
        name,
        src: `/logos/clients/${category}/${encodeURIComponent(file)}`,
        filename: file,
      };
    })
    .sort((a, b) => a.name.localeCompare(b.name));
}

function dedupeByFilename(logos) {
  const seen = new Set();
  return logos.filter((logo) => {
    const key = logo.filename.toLowerCase();
    if (seen.has(key)) return false;
    seen.add(key);
    return true;
  });
}

function formatLogo(logo) {
  return `  { id: '${logo.id}', name: '${logo.name.replace(/'/g, "\\'")}', src: '${logo.src}' }`;
}

function formatArray(name, logos) {
  const entries = logos.map(formatLogo).join(',\n');
  return `export const ${name}: ClientLogo[] = [\n${entries}\n];`;
}

function main() {
  const hcmLogos = scanCategory('HCM');
  const erpLogos = scanCategory('ERP');
  const allLogos = dedupeByFilename([...hcmLogos, ...erpLogos]).sort((a, b) =>
    a.name.localeCompare(b.name),
  );

  const output = `// Auto-generated by scripts/generate-client-logos.mjs, do not edit manually.
// Re-run: npm run logos:generate

export type ClientLogo = {
  id: string;
  name: string;
  src: string;
};

${formatArray('HCM_CLIENT_LOGOS', hcmLogos)}

${formatArray('ERP_CLIENT_LOGOS', erpLogos)}

${formatArray('ALL_CLIENT_LOGOS', allLogos)}
`;

  fs.writeFileSync(outFile, output, 'utf8');

  console.log(`Wrote ${outFile}`);
  console.log(`  HCM: ${hcmLogos.length} logos`);
  console.log(`  ERP: ${erpLogos.length} logos`);
  console.log(`  ALL: ${allLogos.length} logos (deduplicated by filename)`);
}

main();
